#!/usr/bin/env bash
# Load Gemini key from a local file into .env (never committed).
# Usage:
#   ./scripts/setup-env.sh ~/Downloads/gemini.env
#   ./scripts/setup-env.sh ./gemini.env

set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="${1:-$HOME/Downloads/gemini.env}"
DEST="$ROOT/.env"

if [[ ! -f "$SRC" ]]; then
  echo "Missing: $SRC"
  echo "Copy your gemini.env into the project: cp ~/Downloads/gemini.env ./gemini.env"
  exit 1
fi

if grep -qE '^[A-Za-z_]+=' "$SRC"; then
  GEMINI_KEY=$(grep -E '^EXPO_PUBLIC_GEMINI_API_KEY=|^GEMINI_API_KEY=' "$SRC" | head -1 | cut -d= -f2- | tr -d '"' | tr -d "'")
  if [[ -z "${GEMINI_KEY:-}" ]]; then
    GEMINI_KEY=$(grep -E '^[A-Za-z_]+=' "$SRC" | head -1 | cut -d= -f2- | tr -d '"' | tr -d "'")
  fi
else
  GEMINI_KEY=$(tr -d '[:space:]' < "$SRC")
fi

if [[ -z "${GEMINI_KEY:-}" ]]; then
  echo "Could not read API key from $SRC"
  exit 1
fi

cat > "$DEST" <<EOF
# Generated by scripts/setup-env.sh — DO NOT COMMIT
EXPO_PUBLIC_GEMINI_API_KEY=${GEMINI_KEY}
GEMINI_API_KEY=${GEMINI_KEY}
EOF

chmod 600 "$DEST"
echo "Wrote $DEST (gitignored). Key not printed."
